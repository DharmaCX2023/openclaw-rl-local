#!/usr/bin/env bash
set -euo pipefail
cd /root/openclaw-rl-local

ARM="${1:?usage: $0 artifact|or}"
case "$ARM" in
  artifact)
    NAME=artifact-grpo100-clean-serper
    export OPENCLAW_ARTIFACT_GRPO=1
    export OPENCLAW_ARTIFACT_SCORE_MANIFEST=/root/openclaw-rl-local/outputs/artifact_grpo40_20260922/artifact_score_manifest.json
    export OPENCLAW_ARTIFACT_GRPO_STRENGTH=1
    export PORT=30511 OPENCLAW_REMOTE_PROXY_PORT=39511
    export RAY_GCS_PORT=6411 RAY_DASHBOARD_PORT=8311 RAY_CLIENT_PORT=10111
    export RAY_MIN_WORKER_PORT=20000 RAY_MAX_WORKER_PORT=22999
    export SLIME_SGLANG_ENGINE_PORT_BASE=19610 RAY_TEMP_DIR=/tmp/ray-ag100
    ;;
  or)
    NAME=or100-clean-serper
    export OPENCLAW_ARTIFACT_GRPO=0
    unset OPENCLAW_ARTIFACT_SCORE_MANIFEST OPENCLAW_ARTIFACT_GRPO_STRENGTH
    export PORT=30611 OPENCLAW_REMOTE_PROXY_PORT=39611
    export RAY_GCS_PORT=6412 RAY_DASHBOARD_PORT=8312 RAY_CLIENT_PORT=10112
    export RAY_MIN_WORKER_PORT=23000 RAY_MAX_WORKER_PORT=25999
    export SLIME_SGLANG_ENGINE_PORT_BASE=19620 RAY_TEMP_DIR=/tmp/ray-or100
    ;;
  *)
    echo "unknown arm: $ARM" >&2
    exit 2
    ;;
esac

export RUN_STAMP="20261012-${NAME}"
export EXP_NAME="clawgym-${NAME}"
export SAVE_CKPT="${CLEAN_SAVE_CKPT:-/mnt/humf/openclaw-rl-checkpoints/clawgym-${NAME}-20261012}"
export OPENCLAW_SPAN_TRACE_ROOT="${SAVE_CKPT}/span_audit"
export HF_CKPT=/mnt/OpenClaw-RL/hf_ckpt/qwen3-30b-a3b-instruct-clawgym-sft-iter11127
export REF_LOAD="$HF_CKPT"
if [ "${CLEAN_RESUME:-0}" = "1" ]; then
  export LOAD_CKPT="$SAVE_CKPT"
else
  unset LOAD_CKPT
fi
if [ "$ARM" = or ] && [ "${CLEAN_RESUME:-0}" = "1" ]; then
  # Iteration 39 was saved with num_rollout=40. Continuing to step 100 changes
  # Megatron's scheduler length from 2560 to 6400. Constant LR is unchanged;
  # Megatron's own override flag accepts that length.
  export OVERRIDE_OPT_PARAM_SCHEDULER=1
fi

export NUM_GPUS=8 ACTOR_GPUS=4 EXPECTED_ACTOR_GPUS=4 ROLLOUT_GPUS=4 SGLANG_TP=2
export NUM_ROLLOUT="${CLEAN_NUM_ROLLOUT:-100}" ROLLOUT_BATCH_SIZE=8 N_SAMPLES_PER_PROMPT=8
export OPENCLAW_TRAIN_NUM_WORKERS=8 OPENCLAW_TRAIN_SCHEDULING=sequential
export OPENCLAW_TRAIN_SHUFFLE_SEED=0
export OPENCLAW_GATEWAY_IMAGE=clawgym-span-trace:20260921
export OPENCLAW_REMOTE_BASE="/root/clawgym_${NAME}_20261012"
export OPENCLAW_REMOTE_GATEWAY_PORT_MODE=run_scoped
export OPENCLAW_REMOTE_GATEWAY_PORT_MIN=42000 OPENCLAW_REMOTE_GATEWAY_PORT_MAX=62000
export OPENCLAW_REMOTE_DOCKER_START_CONCURRENCY=2 OPENCLAW_REMOTE_SSH_POOL_SIZE=8
export OPENCLAW_CONTEXT_WINDOW=65536 OPENCLAW_TRAJECTORY_MAX_TOKENS=65536
export OPENCLAW_MAX_RESPONSE_TOKENS=8192 OPENCLAW_MAX_AGENT_STEPS=96
export OPENCLAW_MAX_COMPACTION_EVENTS=8 OPENCLAW_CHAT_TURN_TIMEOUT=1200
export OPENCLAW_TOKEN_LEDGER_MODE=enforce
export ROLLOUT_TEMPERATURE=0.7 ROLLOUT_TOP_P=0.8 ROLLOUT_TOP_K=20
export USE_ROUTING_REPLAY=1 USE_ROLLOUT_ROUTING_REPLAY=1 USE_TIS=1
export TIS_CLIP=2.0 TIS_CLIP_LOW=0.0
export SGLANG_ENABLE_DETERMINISTIC_INFERENCE=1 MEGATRON_DETERMINISTIC_MODE=1
export SGLANG_AFFINITY_MODE=task_sample_fixed SGLANG_AFFINITY_SAMPLES_PER_TASK=8
export OPENCLAW_DETERMINISTIC_SAMPLING_SEED_BASE=20260921
export OPENCLAW_DETERMINISTIC_TOOL_CALL_IDS=1
export MAX_TOKENS_PER_GPU=81920 KL_LOSS_MONITOR_INTERVAL=5 ENTROPY_COEF=0.0
export SKIP_EVAL_BEFORE_TRAIN=1 EVAL_INTERVAL=1000

# Megatron checkpoint ids are zero-based rollout ids. Native retain=20 would
# delete semantic step 20 (iter 19), so retain all here and prune externally.
export SAVE_INTERVAL=5 SAVE_RETAIN_INTERVAL=0 OPENCLAW_DISABLE_CHECKPOINT_SAVE=0
export USE_WANDB=0 USE_TENSORBOARD=1
export OPENCLAW_RECORD_ENABLED=1
export OPENCLAW_RECORD_FILE="${SAVE_CKPT}/proxy_records.jsonl"
export OPENCLAW_SAVE_DEBUG_ROLLOUT_DATA="${SAVE_CKPT}/rollout_data/{rollout_id}.pt"

export OPENCLAW_ARTIFACT_GRPO_STRICT=0
export OPENCLAW_TRAIN_EXCLUDE_TASK_IDS=task_0674
export OPENCLAW_CONTAINER_PREFIX="${NAME}"
export OPENCLAW_SERPER_FAIL_CLOSED=1
export OPENCLAW_SERPER_FAIL_CLOSED_ATTEMPTS=3
if [ "$ARM" = artifact ]; then
  export OPENCLAW_ARTIFACT_SCORE_MANIFEST="${SAVE_CKPT}/artifact_score_manifest.runtime.json"
  export OPENCLAW_ARTIFACT_GRPO_DYNAMIC_MANIFEST=1
  export OPENCLAW_ARTIFACT_GRPO_FAIL_CLOSED=1
  if [ ! -f "$OPENCLAW_ARTIFACT_SCORE_MANIFEST" ]; then
    mkdir -p "$SAVE_CKPT"
    printf '{}\n' > "$OPENCLAW_ARTIFACT_SCORE_MANIFEST"
  fi
fi

exec bash clawgym-official/run_span_trace_remote_grpo.sh
